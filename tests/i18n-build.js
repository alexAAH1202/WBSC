// Builds i18n/<lang>.js from i18n/src/<lang>.tsv (one "index<TAB>translation" per line, the index is the position of
// the English string in i18n/en-strings.json) and checks each translation against its English text:
// same {placeholders}, same HTML tags and attributes, same numbers. Run: node tests/i18n-build.js [lang ...]
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const EN = JSON.parse(fs.readFileSync(path.join(root, 'i18n', 'en-strings.json'), 'utf8')).all;
const SKIP = new Set(['Attempt {n}', 'Jordan Smith', 'jordan.smith@example.com', 'WBSC-00000']);   // not shown text
const sig = {
  ph: s => (s.match(/\{[a-z]+\}/g) || []).sort().join(','),
  tags: s => (s.match(/<[^>]+>/g) || []).map(t => t.replace(/\s+/g, ' ')).sort().join('|'),
  nums: s => (s.replace(/<[^>]+>/g, '').match(/\d+/g) || []).sort().join(','),
};
function load(lang) {
  const f = path.join(root, 'i18n', 'src', lang + '.tsv');
  const map = new Map(), errors = [];
  fs.readFileSync(f, 'utf8').split(/\r?\n/).forEach((line, ln) => {
    if (!line.trim() || line.startsWith('#')) return;
    const t = line.indexOf('\t');
    if (t < 0) { errors.push(`${lang}:${ln + 1}: no tab`); return; }
    const i = +line.slice(0, t), tr = line.slice(t + 1).trim();
    if (!(i >= 0 && i < EN.length)) { errors.push(`${lang}:${ln + 1}: bad index ${line.slice(0, t)}`); return; }
    if (map.has(i)) errors.push(`${lang}:${ln + 1}: index ${i} twice`);
    map.set(i, tr);
  });
  return { map, errors };
}
function build(lang) {
  const { map, errors } = load(lang), table = {}, missing = [];
  EN.forEach((en, i) => {
    if (SKIP.has(en)) return;
    const tr = map.get(i);
    if (tr == null || !tr) { missing.push(i); return; }
    for (const k of ['ph', 'tags']) if (sig[k](en) !== sig[k](tr)) errors.push(`${lang} #${i} ${k} differs:\n   EN: ${en.slice(0, 120)}\n   ${lang.toUpperCase()}: ${tr.slice(0, 120)}`);
    // every number in the English text must appear in the translation (a translation may add digits, e.g. "four" written as 4)
    const left = (tr.replace(/<[^>]+>/g, '').match(/\d+/g) || []).slice();
    for (const d of (en.replace(/<[^>]+>/g, '').replace(/\b[123]B\b/g, '').match(/\d+/g) || [])) { const j = left.indexOf(d); if (j < 0) { errors.push(`${lang} #${i} number ${d} missing:\n   EN: ${en.slice(0, 120)}\n   ${lang.toUpperCase()}: ${tr.slice(0, 120)}`); break; } left.splice(j, 1); }
    table[en] = tr;
  });
  if (missing.length) errors.push(`${lang}: ${missing.length} missing: ${missing.slice(0, 30).join(', ')}`);
  fs.writeFileSync(path.join(root, 'i18n', lang + '.js'),
    '// ' + lang + ': generated by tests/i18n-build.js from i18n/src/' + lang + '.tsv. Edit the .tsv, not this file.\n' +
    'window.WBSC_DICT = window.WBSC_DICT || {};\nWBSC_DICT[' + JSON.stringify(lang) + '] = { t: ' + JSON.stringify(table, null, 1) + ' };\n');
  return errors;
}
const langs = process.argv.slice(2).length ? process.argv.slice(2) : fs.readdirSync(path.join(root, 'i18n', 'src')).filter(f => f.endsWith('.tsv') && !f.startsWith('q-')).map(f => f.replace('.tsv', ''));
let bad = 0;
for (const l of langs) { const e = build(l); console.log(l + ': ' + (e.length ? e.length + ' problem(s)' : 'ok')); e.forEach(x => console.log('  ' + x)); bad += e.length; }
process.exit(bad ? 1 : 0);
