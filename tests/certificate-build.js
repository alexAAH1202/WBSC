// Rebuilds certificate/template.js (the official certificate PDF as base64, loaded only when a learner asks for their
// certificate) from certificate/certificate-template.pdf. Run after replacing the PDF: node tests/certificate-build.js
// With --check it only verifies that the committed template.js matches the PDF (used by tests/certificate.test.js).
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const pdf = fs.readFileSync(path.join(root, 'certificate', 'certificate-template.pdf'));
const js = '// Generated by tests/certificate-build.js from certificate-template.pdf. Do not edit.\nwindow.WBSC_CERT_TEMPLATE = "' + pdf.toString('base64') + '";\n';
const out = path.join(root, 'certificate', 'template.js');
if (process.argv.includes('--check')) { process.exit(fs.existsSync(out) && fs.readFileSync(out, 'utf8') === js ? 0 : 1); }
fs.writeFileSync(out, js); console.log('certificate/template.js: ' + js.length + ' characters');
