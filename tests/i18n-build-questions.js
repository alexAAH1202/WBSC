// Builds i18n/q-<lang>.js (the translated quiz text) from i18n/src/q-<lang>.tsv and checks it against i18n/src/q-en.tsv:
// every id present, numbers kept, no empty text. Run: node tests/i18n-export-questions.js first, then
//   node tests/i18n-build-questions.js [lang ...] [--partial]
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), src = path.join(root, 'i18n', 'src');
const read = f => new Map(fs.readFileSync(f, 'utf8').split(/\r?\n/).filter(l => l.trim()).map(l => { const t = l.indexOf('\t'); return [l.slice(0, t), l.slice(t + 1).trim()]; }));
const EN = read(path.join(src, 'q-en.tsv'));
// Questions beyond `draw` in a pool (see questions.js) are optional per language: a language may leave a whole extra question
// untranslated (it is then never drawn in that language). A half-translated extra question is an error.
const BANK = require('vm').runInNewContext(fs.readFileSync(path.join(root, 'questions.js'), 'utf8') + '\n;QUIZ_BANK', {});
const isExtra = id => { const p = id.split('.'); const b = BANK[p[0]]; return !!(b && b.draw && /^\d+$/.test(p[1]) && +p[1] >= b.draw); };
const qid = id => id.split('.').slice(0, 2).join('.');
const args = process.argv.slice(2), partial = args.includes('--partial');
const langs = args.filter(a => !a.startsWith('--'));
const all = langs.length ? langs : fs.readdirSync(src).filter(f => /^q-[a-z]{2}\.tsv$/.test(f) && f !== 'q-en.tsv').map(f => f.slice(2, 4));
let bad = 0;
for (const lang of all) {
  const tr = read(path.join(src, 'q-' + lang + '.tsv')), errors = [], out = {};
  const extrasIn = new Set([...tr.keys()].filter(isExtra).map(qid)); let extrasLeft = new Set();
  for (const [id, en] of EN) {
    const t = tr.get(id);
    if (!t && isExtra(id) && !extrasIn.has(qid(id))) { extrasLeft.add(qid(id)); continue; }
    if (!t) { if (!partial) errors.push('missing ' + id); continue; }
    const left = (t.match(/\d+/g) || []).slice();
    for (const d of (en.replace(/\b[123]B\b/g, '').match(/\d+/g) || [])) { const j = left.indexOf(d); if (j < 0) { errors.push(`${id}: number ${d} missing\n   EN: ${en}\n   ${lang.toUpperCase()}: ${t}`); break; } left.splice(j, 1); }
    const p = id.split('.');
    const a = out[p[0]] = out[p[0]] || { questions: [] };
    if (p[1] === 'title' || p[1] === 'nextLabel') { a[p[1]] = t; continue; }
    const q = a.questions[+p[1]] = a.questions[+p[1]] || { options: [] };
    if (p[2] === 'q') q.q = t; else if (p[2] === 'why') q.why = t; else q.options[+p[2].slice(1)] = t;
  }
  for (const id of tr.keys()) if (!EN.has(id)) errors.push('unknown id ' + id);
  fs.writeFileSync(path.join(root, 'i18n', 'q-' + lang + '.js'),
    '// ' + lang + ' quiz text: generated by tests/i18n-build-questions.js from i18n/src/q-' + lang + '.tsv. Edit the .tsv, not this file.\n' +
    'window.WBSC_QDICT = window.WBSC_QDICT || {};\nWBSC_QDICT[' + JSON.stringify(lang) + '] = ' + JSON.stringify(out) + ';\n');
  console.log(lang + ': ' + (errors.length ? errors.length + ' problem(s)' : 'ok') + ' (' + tr.size + ' of ' + EN.size + ' strings)' + (extrasLeft.size ? '; ' + extrasLeft.size + ' extra pool question(s) not translated yet (not drawn in this language)' : ''));
  errors.slice(0, 20).forEach(e => console.log('  ' + e)); bad += errors.length;
}
process.exit(bad ? 1 : 0);
